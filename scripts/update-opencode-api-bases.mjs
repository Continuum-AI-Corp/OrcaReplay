import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';

// Optional local input makes updating from an already downloaded catalog reproducible/offline.
const source = 'https://models.opencode.ai/api.json';
const catalog = process.argv[2]
  ? JSON.parse(await readFile(process.argv[2], 'utf8'))
  : await fetch(source, { signal: AbortSignal.timeout(30_000) }).then((response) => {
      if (!response.ok) throw new Error(`Catalog HTTP ${response.status}`);
      return response.json();
    });
const bases = new Set();
for (const provider of Object.values(catalog)) {
  if (typeof provider.api === 'string' && provider.api) bases.add(provider.api);
  for (const model of Object.values(provider.models ?? {})) {
    if (typeof model.provider?.api === 'string' && model.provider.api)
      bases.add(model.provider.api);
  }
}
if (!bases.size) throw new Error('Catalog contains no API bases');
await writeFile(
  new URL('../packages/adapters/src/opencode-api-bases.ts', import.meta.url),
  await format(
    `// Generated by scripts/update-opencode-api-bases.mjs from ${source}\n` +
      `// API templates only; no model metadata or credentials.\n` +
      `export const OPENCODE_API_BASES: string[] = ${JSON.stringify([...bases].sort(), null, 2)};\n`,
    { parser: 'typescript', singleQuote: true, printWidth: 100 },
  ),
);
